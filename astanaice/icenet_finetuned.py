def list_directory_tree(start_path):
    """Prints a clear, indented directory tree from the given path."""
    print(f"\n--- Directory Tree from {start_path} ---")
    if not os.path.exists(start_path):
        print(f"Error: Path not found - {start_path}")
        return

    for root, dirs, files in os.walk(start_path):
        level = root.replace(start_path, '').count(os.sep)
        indent = ' ' * 4 * (level)
        print(f'{indent}{os.path.basename(root)}/')
        subindent = ' ' * 4 * (level + 1)
        for f in files:
            print(f'{subindent}{f}')
    print("---------------------------------------")

