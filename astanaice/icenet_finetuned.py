# Part 2: Data Conversion from PNG Masks to YOLO Format
def convert_mask_to_yolo_segmentation(mask_path, save_path, class_id):
    """Converts a single PNG mask to YOLO segmentation format."""
    try:
        mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)

        if mask is None or np.sum(mask) == 0:
            print(f"Warning: Skipping {os.path.basename(mask_path)} as it's an empty or invalid mask.")
            return

        h, w = mask.shape
        contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

        yolo_lines = []
        for contour in contours:
            normalized_points = []
            for point in contour.squeeze():
                x, y = point
                normalized_points.append(x / w)
                normalized_points.append(y / h)

            flattened_points = normalized_points

            yolo_line = f"{class_id} " + " ".join(map(str, flattened_points))
            yolo_lines.append(yolo_line)

        if yolo_lines:
            with open(save_path, 'w') as f:
                f.write("\n".join(yolo_lines))
        else:
            print(f"Warning: No contours found in mask {os.path.basename(mask_path)}. Not creating a label file.")

    except Exception as e:
        print(f"Error processing {os.path.basename(mask_path)}: {e}")

list_directory_tree(DATA_DIR)

print("\nStarting data conversion...")

train_images, train_masks = get_paths(DATA_DIR, 'train')
val_images, val_masks = get_paths(DATA_DIR, 'valid')
test_images, test_masks = get_paths(DATA_DIR, 'test')

paths = {
    'train': {'images': train_images, 'masks': train_masks},
    'valid': {'images': val_images, 'masks': val_masks},
    'test': {'images': test_images, 'masks': test_masks}
}

if os.path.exists(YOLO_DATA_DIR):
    shutil.rmtree(YOLO_DATA_DIR)

for split, split_paths in paths.items():
    img_paths = split_paths['images']
    mask_paths = split_paths['masks']

    yolo_img_dir = os.path.join(YOLO_DATA_DIR, 'images', split)
    yolo_ann_dir = os.path.join(YOLO_DATA_DIR, 'labels', split)
    os.makedirs(yolo_img_dir, exist_ok=True)
    os.makedirs(yolo_ann_dir, exist_ok=True)

    print(f"Converting {len(img_paths)} images for {split} split...")
    for img_path in tqdm(img_paths, desc=f"Converting {split} set"):
        img_name = os.path.basename(img_path)
        base_name = os.path.splitext(img_name)[0]

        mask_name = base_name + '_mask.png'
        mask_path = os.path.join(DATA_DIR, split, mask_name)

        if not os.path.exists(mask_path):
            print(f"Warning: No mask found for {img_name}. Skipping.")
            continue

        shutil.copyfile(img_path, os.path.join(yolo_img_dir, img_name))

        save_path = os.path.join(yolo_ann_dir, base_name + '.txt')
        convert_mask_to_yolo_segmentation(mask_path, save_path, CLASS_LIST.index("ice"))

print("Data conversion complete!")

# Part 3: YOLO Configuration File (data.yaml)
