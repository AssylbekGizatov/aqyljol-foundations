import os
import torch
from ultralytics import YOLO
import cv2
import glob
import random

DATASET_PATH = '/content/drive/MyDrive/snownet/snowdetection.v2i.yolov11/data.yaml'

device = 'cuda' if torch.cuda.is_available() else 'cpu'
print(f"Используется устройство: {device}")

if not os.path.exists(DATASET_PATH):
    print(f"Ошибка: Файл data.yaml не найден по пути: {DATASET_PATH}")
    print("Убедитесь, что вы загрузили папку с датасетом в правильное место.")
else:
    print("Файл конфигурации датасета найден.")

model = YOLO('yolo11n.pt').to(device)

print("\nНачинаю обучение модели...")
try:
    results = model.train(
        data=DATASET_PATH,
        epochs=50,
        imgsz=640,
        patience=20,
        device=device,
        verbose=True
    )
    print("Обучение завершено. Лучшая модель сохранена.")
    trained_model_path = os.path.join('runs', 'detect', 'train', 'weights', 'best.pt')
except Exception as e:
    print(f"Произошла ошибка во время обучения: {e}")
    trained_model_path = None

if trained_model_path and os.path.exists(trained_model_path):
    print("\nНачинаю предсказание на 10 случайных тестовых изображениях.")

    trained_model = YOLO(trained_model_path)

    test_images = glob.glob('/content/drive/MyDrive/snownet/snowdetection.v2i.yolov11/test/images/*.jpg')

    if not test_images:
        print("Ошибка: Тестовые изображения не найдены в папке test/images.")
    else:
        num_images_to_save = 10
        if len(test_images) < num_images_to_save:
            num_images_to_save = len(test_images)
        selected_images = random.sample(test_images, num_images_to_save)

        output_dir = 'yolo_results_snow_detection'
        if not os.path.exists(output_dir):
            os.makedirs(output_dir)

        for i, image_path in enumerate(selected_images):
            print(f"\nОбработка изображения {i+1}/{num_images_to_save}: {os.path.basename(image_path)}")

            results = trained_model(image_path, conf=0.25, verbose=False)

            result_image = results[0].plot()

            output_image_path = os.path.join(output_dir, f'result_{i+1}_{os.path.basename(image_path)}')
            cv2.imwrite(output_image_path, result_image)

            print(f"Изображение с результатом успешно сохранено по пути: {output_image_path}")

else:
    print("\nОшибка: Не удалось найти обученную модель для предсказания.")
    print("Убедитесь, что обучение прошло без критических ошибок.")

import matplotlib.pyplot as plt

def show_metrics_and_visualizations(run_dir):
    metrics_path = os.path.join(run_dir, 'results.csv')
    if os.path.exists(metrics_path):
        print("\nПолные результаты обучения находятся в файле:", metrics_path)

    print("\nГрафики, сгенерированные Ultralytics, находятся в папке:", run_dir)
    print("Вы можете открыть их в Google Colab.")

    metrics_to_show = {
        'Precision-Recall': 'PR_curve.png',
        'F1-Confidence': 'F1_curve.png',
        'Матрица ошибок (Normalized)': 'confusion_matrix_normalized.png'
    }

    plt.figure(figsize=(15, 5))
    for i, (title, filename) in enumerate(metrics_to_show.items()):
        file_path = os.path.join(run_dir, filename)
        if os.path.exists(file_path):
            img = cv2.imread(file_path)
            img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
            ax = plt.subplot(1, 3, i + 1)
            ax.imshow(img)
            ax.set_title(title)
            ax.axis('off')
        else:
            print(f"Предупреждение: Файл '{filename}' не найден.")

    plt.tight_layout()
    plt.show()


results_dir = os.path.join('runs', 'detect', 'train')
if os.path.exists(results_dir):
    show_metrics_and_visualizations(results_dir)
else:
    print("\nПапка с результатами обучения не найдена. Убедитесь, что обучение завершилось успешно.")

def process_my_pics(model_path, pics_dir):
    if not os.path.exists(model_path):
        print(f"Ошибка: Обученная модель не найдена по пути: {model_path}")
        return

    model = YOLO(model_path)

    input_dir = pics_dir
    output_dir = 'my_pics_results'

    if not os.path.exists(input_dir):
        print(f"Ошибка: Папка '{input_dir}' не найдена. Создайте её и добавьте свои изображения.")
        return

    if not os.path.exists(output_dir):
        os.makedirs(output_dir)
        print(f"Создана папка для результатов: {output_dir}")

    new_images = glob.glob(os.path.join(input_dir, '*.jpg'))
    new_images.extend(glob.glob(os.path.join(input_dir, '*.jpeg')))
    new_images.extend(glob.glob(os.path.join(input_dir, '*.png')))

    if not new_images:
        print(f"В папке '{input_dir}' не найдено изображений для обработки.")
        return

    for i, image_path in enumerate(new_images):
        print(f"Обработка изображения {i+1}/{len(new_images)}: {os.path.basename(image_path)}")
        try:
            results = model(image_path, conf=0.25, verbose=False)
            result_image = results[0].plot()
            output_image_path = os.path.join(output_dir, os.path.basename(image_path))
            cv2.imwrite(output_image_path, result_image)
            print(f"Результат сохранен по пути: {output_image_path}")
        except Exception as e:
            print(f"Ошибка при обработке изображения {image_path}: {e}")


process_my_pics(trained_model_path, '/content/drive/MyDrive/snownet/my_pics')

